a = int(input("a = "))
b = int(input("b = "))
c = input("enter your choice = ")

if (c == "+"):
    print("addition = ",a + b)

elif (c == "-"):
    print("Subtraction = ",a - b)

elif(c == "*"):
    print("Multiplication = ",a * b)

elif(c == "/"):
    print("Division = ",a / b)

elif(c == "**"):
    print("Power = ",a ** b)


elif(c == "%"):
    print("Reminder = ",a % b)

elif(c == "//"):
    print("Floor Division = ",a // b)